export function inferFuelFamily(skuOrName: string): FuelFamily {
  const normalized = skuOrName.toUpperCase();
  if (normalized.includes('HSD') || normalized.includes('DIESEL')) {
    return 'DIESEL';
  }
  return 'PETROL';
}

