export function generateFullPostgresDDL(tables: DatabaseTable[] = DATABASE_TABLES): string {
  const header = `-- ============================================================================
-- PETROL PUMP MANAGEMENT SYSTEM — COMPLETE POSTGRESQL 16 SCHEMA
-- Entities: ${tables.length} Tables | ${SQL_ENUMS.length} Enums | ${SQL_VIEWS.length} Analytical Views
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;

`;

  const enumSql = SQL_ENUMS.map(
    (e) => `CREATE TYPE ${e.name} AS ENUM (${e.values.map((v) => `'${v}'`).join(', ')});`
  ).join('\n');

  const tableSql = tables
    .map((table) => {
      const colLines = table.columns.map((col) => {
        const parts = [`  ${col.name} ${col.dataType}`];
        if (!col.nullable) parts.push('NOT NULL');
        if (col.defaultValue) parts.push(`DEFAULT ${col.defaultValue}`);
        if (col.key === 'PK') parts.push('PRIMARY KEY');
        if (col.key === 'UK') parts.push('UNIQUE');
        if (col.references) {
          const [refTable, refCol] = col.references.split('.');
          parts.push(`REFERENCES ${refTable}(${refCol})`);
        }
        return parts.join(' ');
      });

      if (table.name === 'journal_entries') {
        colLines.push('  CONSTRAINT chk_journal_balanced CHECK (total_debit = total_credit)');
      }
      if (table.name === 'shift_nozzle_assignments') {
        colLines.push('  CONSTRAINT chk_meter_monotonic CHECK (closing_meter IS NULL OR closing_meter >= opening_meter)');
      }

      const idxLines = table.indexes
        .map(
          (idx) =>
            `CREATE ${idx.unique ? 'UNIQUE ' : ''}INDEX ${idx.name} ON ${table.name} (${idx.columns.join(', ')});`
        )
        .join('\n');

      return `-- Module: ${table.moduleId} | ${table.description}
CREATE TABLE ${table.name} (
${colLines.join(',\n')}
);
${idxLines}`;
    })
    .join('\n\n');

  const viewSql = SQL_VIEWS.map((v) => `-- View: ${v.name} (${v.purpose})\n${v.sql}`).join('\n\n');

  return `${header}${enumSql}\n\n${tableSql}\n\n${viewSql}\n`;
}
